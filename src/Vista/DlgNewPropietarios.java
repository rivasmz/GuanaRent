    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

        if (txtCedula.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty()
                || txtDireccion.getText().trim().isEmpty() || txtEmail.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Hay campos vacíos");
            return;
        }
        try {
            int cedula = Integer.parseInt(txtCedula.getText());
            Propietario nuevo = new Propietario(
                    cedula,
                    txtNombre.getText(),
                    cmbGenero.getSelectedItem().toString(),
                    txtDireccion.getText(),
                    txtTelefono.getText(),
                    txtEmail.getText()
            );

            if (operacion == 1) {                 // NUEVO
                if (existeCedula(cedula)) {
                    JOptionPane.showMessageDialog(this, "Ya existe un propietario con esa cédula");
                    return;
                }
                listaPropietarios.add(nuevo);
                JOptionPane.showMessageDialog(this, "Propietario agregado");
            } else {                              // EDITAR
                listaPropietarios.set(index, nuevo);
                JOptionPane.showMessageDialog(this, "Propietario editado");
            }
            this.dispose();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La cedula debe ser numerica");
        }


    }//GEN-LAST:event_btnAgregarActionPerformed

    public ArrayList<Propietario> getListaPropietarios() {
        return listaPropietarios;
    }

    private void cargarDatos() {
        txtCedula.setText(String.valueOf(prop.getCedPropiet()));
        txtNombre.setText(prop.getNomPropiet());
        cmbGenero.setSelectedItem(prop.getGenero());
        txtDireccion.setText(prop.getDireccion());
        txtTelefono.setText(prop.getTelefono());
        txtEmail.setText(prop.getEmail());
        txtCedula.setEnabled(false);   // la cédula no se cambia al editar (es la llave)
    }

    private boolean existeCedula(int ced) {
        for (Propietario p : listaPropietarios) {
            if (p.getCedPropiet() == ced) {
                return true;
            }
        }
        return false;
    }

